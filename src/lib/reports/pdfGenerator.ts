import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Entry } from '../../types/index.ts';

export interface CampaignPdfReportOptions {
  title: string;
  subtitle: string;
  filtersUsed: string;
  generatedBy: string;
  wardSummaries: Array<{
    wardName: string;
    target: number;
    captured: number;
    verified: number;
    strong: number;
    coveragePct: string;
  }>;
  priorityStations: Array<{
    stationName: string;
    wardName: string;
    target: number;
    captured: number;
    gap: number;
    urgency: string;
  }>;
}

export function generateCampaignPdfReport(options: CampaignPdfReportOptions): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const greenDark = '#047857'; // Emerald 700
  const grayText = '#4B5563';

  // Header Banner
  doc.setFillColor(4, 120, 87);
  doc.rect(0, 0, 210, 24, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.text('LURAMBI CAMPAIGN FIELD PLATFORM - 2027', 14, 11);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('Kakamega County, Kenya • Member of Parliament Grassroots Campaign', 14, 18);

  // Metadata block
  doc.setTextColor(30, 41, 59);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(options.title, 14, 34);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(75, 85, 99);
  doc.text(`Generated On: ${new Date().toLocaleString()} | Generated By: ${options.generatedBy}`, 14, 40);
  doc.text(`Active Filters: ${options.filtersUsed}`, 14, 45);

  // Section 1: Ward Coverage Table
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(4, 120, 87);
  doc.text('1. Ward-Level Supporter Coverage & Verification Funnel', 14, 54);

  const wardTableRows = options.wardSummaries.map(w => [
    w.wardName,
    w.target.toLocaleString(),
    w.captured.toLocaleString(),
    w.verified.toLocaleString(),
    w.strong.toLocaleString(),
    w.coveragePct
  ]);

  autoTable(doc, {
    startY: 57,
    head: [['Ward Name', 'Voter Target', 'Captured', 'Verified', 'Strong Supporters', 'Coverage %']],
    body: wardTableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [4, 120, 87],
      textColor: [255, 255, 255],
      fontSize: 9,
      fontStyle: 'bold'
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [31, 41, 55]
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252]
    },
    margin: { left: 14, right: 14 }
  });

  // Section 2: Priority Polling Stations (Where gaps are widest)
  const finalY1 = (doc as any).lastAutoTable.finalY + 10;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(4, 120, 87);
  doc.text('2. Priority Polling Stations (Highest Voter Mobilization Deficit)', 14, finalY1);

  const priorityTableRows = options.priorityStations.map(s => [
    s.stationName,
    s.wardName,
    s.target.toLocaleString(),
    s.captured.toLocaleString(),
    s.gap.toLocaleString(),
    s.urgency
  ]);

  autoTable(doc, {
    startY: finalY1 + 4,
    head: [['Polling Station', 'Ward', 'Target Electorate', 'Captured', 'Deficit / Gap', 'Priority Level']],
    body: priorityTableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontSize: 8.5,
      fontStyle: 'bold'
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [31, 41, 55]
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252]
    },
    margin: { left: 14, right: 14 }
  });

  // Confidentiality & Legal Footer
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(7.5);
    doc.setTextColor(156, 163, 175);
    doc.text(
      'CONFIDENTIAL - LURAMBI CAMPAIGN INTELLIGENCE - PROTECTED UNDER KENYA DATA PROTECTION ACT 2019',
      14,
      290
    );
    doc.text(`Page ${i} of ${pageCount}`, 190, 290, { align: 'right' });
  }

  doc.save(`Lurambi_Campaign_Field_Report_${Date.now()}.pdf`);
}
